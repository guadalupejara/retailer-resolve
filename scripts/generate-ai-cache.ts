// Generates src/lib/ai-cache.ts by calling the explain path once per hero case (live Gemini).
// Uses the same primary, retry and backup path as the server function. Generation runs offline, so it
// allows AI_CACHE_BUDGET_MS (default 60 s) instead of the 20 s live budget, and it fails rather than
// caching a saved response.
// Run: npm run ai:cache   (reads SUPABASE_* and GEMINI_* from .env.local)
import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { fetchSeed, type SeedDb } from "../src/lib/seed";
import { explainCaseCore, extractSystemPrompt, type AiExplanation } from "../src/lib/ai-explain";

const HERO_CASES = ["WMT-001", "AMZ-001", "WMT-017"];
const budgetMs = Number(process.env["AI_CACHE_BUDGET_MS"] ?? 60_000);

const url = process.env["SUPABASE_URL"] ?? process.env["VITE_SUPABASE_URL"];
const key = process.env["SUPABASE_PUBLISHABLE_KEY"] ?? process.env["VITE_SUPABASE_PUBLISHABLE_KEY"];
const apiKey = process.env["GEMINI_API_KEY"];
const model = process.env["GEMINI_MODEL"];
const fallbackModel = process.env["GEMINI_FALLBACK_MODEL"];
if (!url || !key) throw new Error("SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY must be set in .env.local");
if (!apiKey || !model) throw new Error("GEMINI_API_KEY and GEMINI_MODEL must be set in .env.local");

const systemPrompt = extractSystemPrompt(
  readFileSync(new URL("../mock-backend/ai/explain-prompt.md", import.meta.url), "utf8"),
);
const seed = await fetchSeed(createClient(url, key) as unknown as SeedDb);

const cache: Record<string, AiExplanation> = {};
for (const id of HERO_CASES) {
  const t0 = Date.now();
  const logs: string[] = [];
  const out = await explainCaseCore({
    seed, id, systemPrompt, apiKey, model, fallbackModel, cache: {}, budgetMs, log: (m) => logs.push(m),
  });
  if (out.mode !== "live") throw new Error(`${id}: expected a live Gemini reply, got ${out.mode}. ${logs.join(" | ")}`);
  cache[id] = out.explanation;
  for (const l of logs) console.log(`    log: ${l}`);
  console.log(`${id}: ${out.path} reply in ${((Date.now() - t0) / 1000).toFixed(1)} s, headline: ${out.explanation.headline}`);
}

const header = `// Generated by scripts/generate-ai-cache.ts from live Gemini replies (model ${model})
// on ${new Date().toISOString()}. Do not edit by hand. Regenerate with: npm run ai:cache`;
writeFileSync(
  new URL("../src/lib/ai-cache.ts", import.meta.url),
  `${header}\nimport type { AiExplanation } from "./ai-explain";\n\nexport const AI_CACHE: Record<string, AiExplanation> = ${JSON.stringify(cache, null, 2)};\n`,
);
console.log(`Wrote src/lib/ai-cache.ts with ${Object.keys(cache).length} cases.`);
